export const GLYPH_H = 8;
const SPACE_W = 3;
const cache = new Map();

function parse(ch) {
  if (cache.has(ch)) return cache.get(ch);
  let g;
  if (ch === ' ') {
    g = { w: SPACE_W, px: new Uint8Array(SPACE_W * GLYPH_H) };
  } else {
    const src = G[ch] ?? G[ch.normalize('NFD')[0]] ?? G['?'];
    const rows = src.split(' ');
    let lo = 5, hi = -1;
    for (const r of rows) for (let x = 0; x < 5; x++) if (r[x] === '#') { lo = Math.min(lo, x); hi = Math.max(hi, x); }
    if (hi < 0) lo = 0;
    const w = Math.max(0, hi - lo + 1);
    const px = new Uint8Array(w * GLYPH_H);
    rows.forEach((r, y) => { for (let x = 0; x < w; x++) if (r[lo + x] === '#') px[y * w + x] = 1; });
    g = { w, px };
  }
  cache.set(ch, g);
  return g;
}

/** Render one line in the pixel font. Returns an alpha mask {w, h, a} (a: 0 or 255). */
export function pixelLine(text, scale = 1) {
  const glyphs = [...text].map(parse);
  const w1 = glyphs.reduce((s, g) => s + g.w, 0) + Math.max(0, glyphs.length - 1);
  const w = w1 * scale, h = GLYPH_H * scale;
  const a = new Uint8Array(Math.max(w, 0) * h);
  let cx = 0;
  for (const g of glyphs) {
    for (let y = 0; y < GLYPH_H; y++)
      for (let x = 0; x < g.w; x++)
        if (g.px[y * g.w + x])
          for (let dy = 0; dy < scale; dy++)
            for (let dx = 0; dx < scale; dx++) a[(y * scale + dy) * w + (cx + x) * scale + dx] = 255;
    cx += g.w + 1;
  }
  return { w, h, a };
}
